// Target implements adapters.TargetAdapter for PostgreSQL.
type Target struct {
	db      *sql.DB
	config  adapters.ConnectionConfig
	mu      sync.RWMutex
	schemas map[string]*adapters.TableSchema // cached for upsert key resolution
	useCopy bool                             // use COPY instead of INSERT; only safe when target table is clean

	xmlOnce sync.Once
	xmlOK   bool // the server can store xml values (see columnType)
}

// columnType is the column type CreateTable/AlterTable use for a source
// type. A server built without libxml (YugabyteDB 2025.2, say) has an xml
// type but refuses every non-NULL value with "unsupported XML feature"
// (0A000), so there an xml column is created as text, which holds the same
// serialized document.
func (t *Target) columnType(ctx context.Context, srcType string) string {
	pgType := mapTypeToPostgres(srcType)
	if strings.ToLower(pgType) != "xml" {
		return pgType
	}
	t.xmlOnce.Do(func() {
		_, err := t.db.ExecContext(ctx, `SELECT '<x/>'::xml`)
		var pqErr *pq.Error
		t.xmlOK = !(errors.As(err, &pqErr) && pqErr.Code == "0A000")
	})
	if !t.xmlOK {
		return "text"
	}
	return pgType
}

// EnableCopy switches WriteBatch to use the PostgreSQL COPY protocol instead of
// multi-row INSERT. Implements adapters.BulkCopyWriter. Must only be called when
// the target table is guaranteed empty (truncate or recreate-schema mode).
func (t *Target) EnableCopy() {
	t.useCopy = true
}

func NewTarget() adapters.TargetAdapter {
	return &Target{schemas: make(map[string]*adapters.TableSchema)}
}

func (t *Target) Connect(ctx context.Context, config adapters.ConnectionConfig) error {
	db, err := sql.Open("postgres", buildDSN(config))
	if err != nil {
		return fmt.Errorf("postgres open: %w", err)
	}
	t.db = db
	t.config = config
	return t.Ping(ctx)
}

func (t *Target) Close() error {
	if t.db != nil {
		return t.db.Close()
	}
	return nil
}

func (t *Target) Ping(ctx context.Context) error {
	return t.db.PingContext(ctx)
}

func (t *Target) ListTables(ctx context.Context) ([]adapters.TableSchema, error) {
	names, err := listTables(ctx, t.db, t.config.Schema == "")
	if err != nil {
		return nil, err
	}
	tables := make([]adapters.TableSchema, 0, len(names))
	for _, name := range names {
		schema, err := getSchema(ctx, t.db, name)
		if err != nil {
			return nil, err
		}
		tables = append(tables, *schema)
	}
	return tables, nil
}

func (t *Target) GetSchema(ctx context.Context, table string) (*adapters.TableSchema, error) {
	return getSchema(ctx, t.db, table)
}

func (t *Target) CreateTable(ctx context.Context, schema *adapters.TableSchema) error {
	// The table's schema may not exist yet: a "schema.table" name from a
	// source migrating all its schemas, or the configured Schema (which,
	// missing, leaves current_schema() NULL and a bare name nowhere to go).
	if s, _ := splitName(schema.Name); s != "" || t.config.Schema != "" {
		if s == "" {
			s = t.config.Schema
		}
		if _, err := t.db.ExecContext(ctx, "CREATE SCHEMA IF NOT EXISTS "+quote(s)); err != nil {
			return fmt.Errorf("create schema %s: %w", s, err)
		}
	}
	defs := make([]string, 0, len(schema.Columns))
	var pks []string
	for _, c := range schema.Columns {
		pgType := t.columnType(ctx, c.Type)
		def := fmt.Sprintf(`%s %s`, quote(c.Name), pgType)
		if !c.Nullable {
			def += " NOT NULL"
		}
		if c.Identity && isIntegerType(pgType) {
			// BY DEFAULT, not ALWAYS: the copy and a live stream write
			// the source's keys into it.
			def += " GENERATED BY DEFAULT AS IDENTITY"
		} else if d, ok := adapters.TranslateDefault(c, adapters.DialectPostgres, pgType); ok {
			def += " DEFAULT " + d
		}
		defs = append(defs, def)
		if c.PrimaryKey {
			pks = append(pks, quote(c.Name))
		}
	}
	if len(pks) > 0 {
		defs = append(defs, fmt.Sprintf("PRIMARY KEY (%s)", strings.Join(pks, ", ")))
	}

	query := fmt.Sprintf(`CREATE TABLE IF NOT EXISTS %s (%s)`,
		qualify(schema.Name), strings.Join(defs, ", "))
	if _, err := t.db.ExecContext(ctx, query); err != nil {
		return fmt.Errorf("create table %s: %w", schema.Name, err)
	}

	t.mu.Lock()
	t.schemas[schema.Name] = schema
	t.mu.Unlock()
	return nil
}

func (t *Target) CreateIndexes(ctx context.Context, table string, indexes []adapters.IndexDef) error {
	for _, idx := range indexes {
		cols := make([]string, len(idx.Columns))
		for i, c := range idx.Columns {
			cols[i] = quote(c)
		}
		unique := ""
		if idx.Unique {
			unique = "UNIQUE "
		}
		if err := t.dropInvalidIndex(ctx, table, idx.Name); err != nil {
			return err
		}
		query := fmt.Sprintf(`CREATE %sINDEX IF NOT EXISTS %s ON %s (%s)`,
			unique, quote(idx.Name), qualify(table), strings.Join(cols, ", "))
		if _, err := t.db.ExecContext(ctx, query); err != nil {
			return fmt.Errorf("create index %s on %s: %w", idx.Name, table, err)
		}
	}
	return nil
}

// dropInvalidIndex drops the index name in table's schema if a build of it
// failed or was cancelled part way: YugabyteDB (whose CREATE INDEX on a table
// with rows builds online) and PostgreSQL's CREATE INDEX CONCURRENTLY leave
// such an index behind, marked invalid: never used, and a unique one enforces
// nothing. CREATE INDEX IF NOT EXISTS would take it as already done, so a
// retry or resume would quietly keep it.
func (t *Target) dropInvalidIndex(ctx context.Context, table, name string) error {
	schema, _ := splitName(table)
	var invalid bool
	err := t.db.QueryRowContext(ctx, `
		SELECT NOT i.indisvalid
		FROM pg_index i
		JOIN pg_class c ON c.oid = i.indexrelid
		JOIN pg_namespace n ON n.oid = c.relnamespace
		WHERE n.nspname = `+schemaExpr(2)+` AND c.relname = $1`, name, schema).Scan(&invalid)
	if errors.Is(err, sql.ErrNoRows) || (err == nil && !invalid) {
		return nil
	}
	if err != nil {
		return fmt.Errorf("check index %s on %s: %w", name, table, err)
	}
	slog.Warn("postgres: dropping invalid index left by an earlier failed build", "index", name, "table", table)
	qualified := quote(name)
	if schema != "" {
		qualified = quote(schema) + "." + quote(name)
	}
	if _, err := t.db.ExecContext(ctx, `DROP INDEX IF EXISTS `+qualified); err != nil {
		return fmt.Errorf("drop invalid index %s on %s: %w", name, table, err)
	}
	return nil
}

func (t *Target) CreateConstraints(ctx context.Context, table string, fks []adapters.ForeignKey, checks []adapters.CheckConstraint) error {
	tableSchema, tableName := splitName(table)
	for _, fk := range fks {
		var count int
		if err := t.db.QueryRowContext(ctx, `
			SELECT COUNT(*) FROM information_schema.table_constraints
			WHERE constraint_schema = `+schemaExpr(3)+` AND table_name = $1 AND constraint_name = $2`,
			tableName, fk.Name, tableSchema).Scan(&count); err != nil {
			return fmt.Errorf("check fk existence %s: %w", fk.Name, err)
		}
		if count > 0 {
			continue // already exists — idempotent on resume
		}
		fromCols := make([]string, len(fk.Columns))
		toCols := make([]string, len(fk.RefColumns))
		for i, c := range fk.Columns {
			fromCols[i] = quote(c)
		}
		for i, c := range fk.RefColumns {
			toCols[i] = quote(c)
		}
		q := fmt.Sprintf(
			`ALTER TABLE %s ADD CONSTRAINT %s FOREIGN KEY (%s) REFERENCES %s (%s)`,
			qualify(table), quote(fk.Name),
			strings.Join(fromCols, ", "),
			qualify(fk.RefTable),
			strings.Join(toCols, ", "),
		)
		if fk.OnDelete != "" && fk.OnDelete != "NO ACTION" {
			q += " ON DELETE " + fk.OnDelete
		}
		if fk.OnUpdate != "" && fk.OnUpdate != "NO ACTION" {
			q += " ON UPDATE " + fk.OnUpdate
		}
		if _, err := t.db.ExecContext(ctx, q); err != nil {
			return fmt.Errorf("add foreign key %s.%s: %w", table, fk.Name, err)
		}
	}

	for _, chk := range checks {
		var count int
		if err := t.db.QueryRowContext(ctx, `
			SELECT COUNT(*) FROM information_schema.table_constraints
			WHERE constraint_schema = `+schemaExpr(3)+` AND table_name = $1 AND constraint_name = $2`,
			tableName, chk.Name, tableSchema).Scan(&count); err != nil {
			return fmt.Errorf("check constraint existence %s: %w", chk.Name, err)
		}
		if count > 0 {
			continue
		}
		q := fmt.Sprintf(`ALTER TABLE %s ADD CONSTRAINT %s CHECK (%s)`,
			qualify(table), quote(chk.Name), chk.Expression)
		if _, err := t.db.ExecContext(ctx, q); err != nil {
			return fmt.Errorf("add check constraint %s.%s: %w", table, chk.Name, err)
		}
	}
	return nil
}

func (t *Target) DropTable(ctx context.Context, table string) error {
	_, err := t.db.ExecContext(ctx, fmt.Sprintf(`DROP TABLE IF EXISTS %s CASCADE`, qualify(table)))
	return err
}

func (t *Target) TruncateTable(ctx context.Context, table string) error {
	_, err := t.db.ExecContext(ctx, fmt.Sprintf(`TRUNCATE TABLE %s`, qualify(table)))
	return err
}

func (t *Target) AlterTable(ctx context.Context, table string, changes []adapters.SchemaChange) error {
	for _, change := range changes {
		var query string
		switch change.Type {
		case adapters.ChangeAddColumn:
			pgType := t.columnType(ctx, change.Column.Type)
			def := fmt.Sprintf(`%s %s`, quote(change.Column.Name), pgType)
			if !change.Column.Nullable {
				def += " NOT NULL"
			}
			if d, ok := adapters.TranslateDefault(change.Column, adapters.DialectPostgres, pgType); ok {
				def += " DEFAULT " + d
			}
			query = fmt.Sprintf(`ALTER TABLE %s ADD COLUMN %s`, qualify(table), def)
		case adapters.ChangeDropColumn:
			query = fmt.Sprintf(`ALTER TABLE %s DROP COLUMN %s`,
				qualify(table), quote(change.Column.Name))
		case adapters.ChangeAlterColumn:
			pgType := t.columnType(ctx, change.Column.Type)
			query = fmt.Sprintf(`ALTER TABLE %s ALTER COLUMN %s TYPE %s`,
				qualify(table), quote(change.Column.Name), pgType)
		default:
			return fmt.Errorf("unsupported change type: %s", change.Type)
		}
		if _, err := t.db.ExecContext(ctx, query); err != nil {
			return fmt.Errorf("alter table %s (%s %s): %w",
				table, change.Type, change.Column.Name, err)
		}
	}
	return nil
}

func (t *Target) WriteBatch(ctx context.Context, table string, batch *adapters.Batch) error {
	if len(batch.Records) == 0 {
		return nil
	}
	if t.useCopy {
		return t.writeBatchCopy(ctx, table, batch)
	}

	tx, err := t.db.BeginTx(ctx, nil)
	if err != nil {
		return fmt.Errorf("begin tx: %w", err)
	}
	defer tx.Rollback()
	if err := t.upsertTx(ctx, tx, table, batch.Records); err != nil {
		return err
	}
	return tx.Commit()
}

// upsertTx writes records to table in tx with the upsert WriteBatch uses; a
// live migration's apply (ChangeTx.Upsert) runs it in its own transaction.
func (t *Target) upsertTx(ctx context.Context, tx *sql.Tx, table string, records []map[string]interface{}) error {
	schema, err := t.cachedSchema(ctx, table)
	if err != nil {
		return err
	}
	pks := pkColumns(schema)

	// Derive columns from the schema, not from Records[0].
	// This ensures all columns are included even if the first record
	// is missing some fields (which would become NULL).
	cols := make([]string, 0, len(schema.Columns))
	for _, c := range schema.Columns {
		cols = append(cols, c.Name)
	}

	// Build INSERT ... ON CONFLICT (...) DO UPDATE SET ...
	quotedCols := make([]string, len(cols))
	for i, c := range cols {
		quotedCols[i] = quote(c)
	}

	// PostgreSQL uses $1, $2, ... placeholders.
	placeholders := make([]string, len(cols))
	for i := range cols {
		placeholders[i] = fmt.Sprintf("$%d", i+1)
	}

	var upsertClause string
	if len(pks) > 0 {
		quotedPKs := make([]string, len(pks))
		for i, pk := range pks {
			quotedPKs[i] = quote(pk)
		}
		setClauses := make([]string, 0, len(cols))
		pkSet := map[string]bool{}
		for _, pk := range pks {
			pkSet[pk] = true
		}
		for _, col := range cols {
			if !pkSet[col] {
				setClauses = append(setClauses, fmt.Sprintf(`%s = EXCLUDED.%s`, quote(col), quote(col)))
			}
		}
		if len(setClauses) > 0 {
			upsertClause = fmt.Sprintf(`ON CONFLICT (%s) DO UPDATE SET %s`,
				strings.Join(quotedPKs, ", "), strings.Join(setClauses, ", "))
		} else {
			upsertClause = fmt.Sprintf(`ON CONFLICT (%s) DO NOTHING`, strings.Join(quotedPKs, ", "))
		}
	} else {
		upsertClause = "ON CONFLICT DO NOTHING"
	}

	// PostgreSQL allows at most 65535 bind parameters per query.
	// Chunk records so each INSERT stays under that limit.
	maxRows := 65535 / len(cols)
	if maxRows < 1 {
		maxRows = 1
	}

	for start := 0; start < len(records); start += maxRows {
		end := start + maxRows
		if end > len(records) {
			end = len(records)
		}
		chunk := records[start:end]

		rowPlaceholders := make([]string, len(chunk))
		allVals := make([]interface{}, 0, len(chunk)*len(cols))
		for i, rec := range chunk {
			ph := make([]string, len(cols))
			for j := range cols {
				ph[j] = fmt.Sprintf("$%d", i*len(cols)+j+1)
			}
			rowPlaceholders[i] = "(" + strings.Join(ph, ", ") + ")"
			for _, col := range cols {
				allVals = append(allVals, rec[col])
			}
		}

		chunkQuery := fmt.Sprintf(`INSERT INTO %s (%s) VALUES %s %s`,
			qualify(table),
			strings.Join(quotedCols, ", "),
			strings.Join(rowPlaceholders, ", "),
			upsertClause,
		)
		if _, err := tx.ExecContext(ctx, chunkQuery, allVals...); err != nil {
			return fmt.Errorf("insert chunk into %s: %w", table, err)
		}
	}

	return nil
}

// writeBatchCopy uses the PostgreSQL COPY protocol to stream rows into the table.
// This is 10–50x faster than multi-row INSERT but does not support ON CONFLICT,
// so it is only valid when the target table is guaranteed empty.
func (t *Target) writeBatchCopy(ctx context.Context, table string, batch *adapters.Batch) error {
	// Fetch schema first so we can derive columns from it, not from Records[0].
	// This ensures all columns are included even if the first record is missing
	// some fields (which would become NULL).
	schema, err := t.cachedSchema(ctx, table)
	if err != nil {
		return fmt.Errorf("copy into %s: %w", table, err)
	}

	cols := make([]string, 0, len(schema.Columns))
	isBytea := make(map[string]bool, len(schema.Columns))
	for _, c := range schema.Columns {
		cols = append(cols, c.Name)
		// lib/pq's COPY encoder always renders a []byte value as a hex-escaped
		// bytea literal, regardless of the target column's actual type. Source
		// drivers commonly hand back non-binary columns (e.g. MySQL DECIMAL) as
		// []byte, which would otherwise get corrupted into bytea gibberish for
		// any non-bytea column. Convert those to string first so they're copied
		// as plain text; only genuine bytea columns keep []byte encoding.
		isBytea[c.Name] = strings.EqualFold(c.Type, "bytea")
	}

	tx, err := t.db.BeginTx(ctx, nil)
	if err != nil {
		return fmt.Errorf("begin tx: %w", err)
	}
	defer tx.Rollback()

	copySchema, copyTable := splitName(table)
	copyStmt := pq.CopyIn(copyTable, cols...)
	if copySchema != "" {
		copyStmt = pq.CopyInSchema(copySchema, copyTable, cols...)
	}
	stmt, err := tx.PrepareContext(ctx, copyStmt)
	if err != nil {
		return fmt.Errorf("prepare copy into %s: %w", table, err)
	}
	defer stmt.Close()

	vals := make([]interface{}, len(cols))
	for _, rec := range batch.Records {
		for i, col := range cols {
			v := rec[col]
			if b, ok := v.([]byte); ok && !isBytea[col] {
				v = string(b)
			}
			vals[i] = v
		}
		if _, err := stmt.ExecContext(ctx, vals...); err != nil {
			return fmt.Errorf("copy row into %s: %w", table, err)
		}
	}

	// Flush the buffered COPY data to the server.
	if _, err := stmt.ExecContext(ctx); err != nil {
		return fmt.Errorf("copy flush %s: %w", table, err)
	}

	return tx.Commit()
}

func (t *Target) CheckPermissions(ctx context.Context) (*adapters.PermissionCheck, error) {
	check := &adapters.PermissionCheck{}

	// Probe: read
	if err := t.db.QueryRowContext(ctx, `SELECT 1 FROM information_schema.tables LIMIT 1`).Err(); err != nil {
		check.Errors = append(check.Errors, fmt.Sprintf("read check failed: %v", err))
		return check, nil
	}
	check.CanRead = true

	// Probe: create table
	_, err := t.db.ExecContext(ctx, `CREATE TEMP TABLE IF NOT EXISTS _xferdb_probe (id SERIAL PRIMARY KEY)`)
	if err != nil {
		check.Errors = append(check.Errors, fmt.Sprintf("create table check failed: %v", err))
		return check, nil
	}
	check.CanCreateTable = true

	// Probe: write
	_, err = t.db.ExecContext(ctx, `INSERT INTO _xferdb_probe DEFAULT VALUES`)
	if err != nil {
		check.Errors = append(check.Errors, fmt.Sprintf("write check failed: %v", err))
	} else {
		check.CanWrite = true
	}

	t.db.ExecContext(ctx, `DROP TABLE IF EXISTS _xferdb_probe`) //nolint:errcheck
	return check, nil
}

// cachedSchema returns the schema for a table, fetching and caching it if needed.
func (t *Target) cachedSchema(ctx context.Context, table string) (*adapters.TableSchema, error) {
	t.mu.RLock()
	schema, ok := t.schemas[table]
	t.mu.RUnlock()
	if ok {
		return schema, nil
	}

	schema, err := getSchema(ctx, t.db, table)
	if err != nil {
		return nil, err
	}

	t.mu.Lock()
	t.schemas[table] = schema
	t.mu.Unlock()
	return schema, nil
}

func (t *Target) GetInfo(ctx context.Context) (*adapters.DatabaseInfo, error) {
	info := &adapters.DatabaseInfo{Type: "PostgreSQL"}

	// Get version
	var version string
	if err := t.db.QueryRowContext(ctx, `SHOW server_version`).Scan(&version); err == nil {
		info.Version = version
	}

	// Get current database name
	var dbName string
	if err := t.db.QueryRowContext(ctx, `SELECT current_database()`).Scan(&dbName); err == nil {
		info.Database = dbName
	}

	var schema sql.NullString
	t.db.QueryRowContext(ctx, `SELECT current_schema()`).Scan(&schema) //nolint:errcheck
	if t.config.Schema != "" {
		info.Schema = schema.String
	}

	// Get host info from config or inet_server_addr()
	if t.config.Host != "" {
		port := t.config.Port
		if port == 0 {
			port = DefaultPort(t.config.Type)
		}
		info.Host = fmt.Sprintf("%s:%d", t.config.Host, port)
	} else {
		var host sql.NullString
		var port sql.NullInt64
		t.db.QueryRowContext(ctx, `SELECT inet_server_addr(), inet_server_port()`).Scan(&host, &port)
		if host.Valid {
			info.Host = fmt.Sprintf("%s:%d", host.String, port.Int64)
		}
	}

	// Count tables
	tables, err := listTables(ctx, t.db, t.config.Schema == "")
	if err == nil {
		info.Tables = len(tables)
	}

	// Get database size
	var sizeBytes int64
	if err := t.db.QueryRowContext(ctx, `SELECT pg_database_size(current_database())`).Scan(&sizeBytes); err == nil {
		info.SizeBytes = sizeBytes
		info.SizeHuman = humanSize(sizeBytes)
	}

	// Check SSL status
	var ssl string
	if err := t.db.QueryRowContext(ctx, `SHOW ssl`).Scan(&ssl); err == nil {
		if ssl == "on" {
			info.SSL = "enabled"
		} else {
			info.SSL = "disabled"
		}
	}

	return info, nil
}

// CreateDatabase implements adapters.DatabaseCreator. Postgres has no
// CREATE DATABASE IF NOT EXISTS, so duplicate_database (42P04) counts as done.
func (t *Target) CreateDatabase(ctx context.Context, name string) error {
	if _, err := t.db.ExecContext(ctx, "CREATE DATABASE "+quote(name)); err != nil {
		if strings.Contains(err.Error(), "42P04") {
			return nil
		}
		return fmt.Errorf("create database %s: %w", name, err)
	}
	return nil
}
