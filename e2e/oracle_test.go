// Oracle as a migration source (#190), end to end through the REST API:
// seed a schema covering Oracle's types, keys and indexes, migrate it, and
// check the validation that runs after the migration and a few converted
// values on the target.
//
//	XFERDB_TEST_ORACLE     an Oracle login's DSN, e.g. oracle://xferdb:pw@localhost:1521/FREEPDB1
//	                       (its own schema gets XFDB_* tables, dropped first)
//	XFERDB_TEST_ORACLE_PG     optional: also migrate to this PostgreSQL DSN
//	XFERDB_TEST_ORACLE_MYSQL  optional: also migrate to this MySQL DSN
//	                          (databases the test may fill with tables)
//
// A SQLite file is always a target too.

