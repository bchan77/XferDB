var oracleTables = []string{"xfdb_customers", "xfdb_orders", "xfdb_order_lines", "xfdb_events", "XfdbMixed", "xfdb_docs"}

func segmentWorkers(target string) int {
	if strings.HasSuffix(target, "-single") {
		return 1
	}
	return 3
}

func seedOracle(t *testing.T, ctx context.Context, dsn string) {
	t.Helper()
	db, err := sql.Open("oracle", dsn)
	if err != nil {
		t.Fatal(err)
	}
	defer db.Close()
	for _, tbl := range []string{"XFDB_ORDER_LINES", "XFDB_ORDERS", "XFDB_CUSTOMERS", "XFDB_EVENTS", `"XfdbMixed"`, "XFDB_DOCS"} {
		db.ExecContext(ctx, "DROP TABLE "+tbl+" CASCADE CONSTRAINTS PURGE") //nolint:errcheck // may not exist
	}
	for _, stmt := range oracleSeed {
		if _, err := db.ExecContext(ctx, stmt); err != nil {
			t.Fatalf("seed: %v\n%s", err, stmt)
		}
	}
}

func TestOracleSource(t *testing.T) {
	oraDSN := os.Getenv("XFERDB_TEST_ORACLE")
	if oraDSN == "" {
		t.Skip("XFERDB_TEST_ORACLE not set")
	}
	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Minute)
	defer cancel()
	seedOracle(t, ctx, oraDSN)

	targets := map[string]map[string]any{
		"sqlite": {"type": "sqlite", "dsn": filepath.Join(t.TempDir(), "target.db")},
		// One segment worker: tables with a primary key are read by key
		// (engine keyPager), not split into PK ranges.
		"sqlite-single": {"type": "sqlite", "dsn": filepath.Join(t.TempDir(), "single.db")},
	}
	if pg := os.Getenv("XFERDB_TEST_ORACLE_PG"); pg != "" {
		targets["postgres"] = map[string]any{"type": "postgres", "dsn": pg}
	}
	if my := os.Getenv("XFERDB_TEST_ORACLE_MYSQL"); my != "" {
		targets["mysql"] = map[string]any{"type": "mysql", "dsn": my}
	}
	for name, target := range targets {
		t.Run(name, func(t *testing.T) {
			stateDB := openStateDB(t)
			defer stateDB.Close()
			ts := httptest.NewServer(api.NewServer(stateDB, slog.Default()).Handler())
			defer ts.Close()

			proj := postJSON(t, ts.URL+"/api/v1/projects", map[string]any{
				"name":          "oracle-" + name,
				"source_config": map[string]any{"type": "oracle", "dsn": oraDSN},
				"target_config": target,
				"transfer_config": map[string]any{
					"batch_size": 400, "table_workers": 2, "segment_workers": segmentWorkers(name), "validation_level": "L3",
				},
			}, http.StatusCreated)
			pre := postJSON(t, ts.URL+"/api/v1/projects/"+proj["id"].(string)+"/preflight", map[string]any{}, http.StatusOK)
			if pre["status"] == "failed" {
				t.Fatalf("preflight failed: %v", pre)
			}
			mig := postJSON(t, ts.URL+"/api/v1/projects/"+proj["id"].(string)+"/migrations", map[string]any{
				"recreate_schema": true, "tables": oracleTables,
			}, http.StatusCreated)
			migID := mig["id"].(string)
			for deadline := time.Now().Add(3 * time.Minute); ; time.Sleep(time.Second) {
				var m map[string]any
				getJSON(t, ts.URL+"/api/v1/migrations/"+migID, &m)
				if m["status"] == "completed" {
					break
				}
				if m["status"] == "failed" || time.Now().After(deadline) {
					t.Fatalf("migration %v: %v", m["status"], m["error"])
				}
			}

			// The validation that follows a completed migration: every table passes.
			var v map[string]any
			for deadline := time.Now().Add(2 * time.Minute); ; time.Sleep(time.Second) {
				var list []map[string]any
				getJSON(t, ts.URL+"/api/v1/migrations/"+migID+"/validations", &list)
				if len(list) > 0 {
					getJSON(t, ts.URL+"/api/v1/validations/"+list[0]["id"].(string), &v)
					if s := v["status"]; s == "completed" || s == "failed" {
						break
					}
				}
				if time.Now().After(deadline) {
					t.Fatal("no finished validation")
				}
			}
			tables, _ := v["tables"].([]any)
			if len(tables) != len(oracleTables) {
				t.Errorf("validation covered %d tables, want %d: %v", len(tables), len(oracleTables), v)
			}
			for _, x := range tables {
				tb := x.(map[string]any)
				if tb["result"] != "pass" {
					var diffs any
					getJSON(t, fmt.Sprintf("%s/api/v1/validations/%s/tables/%s/diffs", ts.URL, v["id"], tb["table_name"]), &diffs)
					d, _ := json.Marshal(diffs)
					if len(d) > 1500 {
						d = d[:1500]
					}
					t.Errorf("validation of %v: %v (%v)\n%s", tb["table_name"], tb["result"], tb["detail"], d)
				}
			}

			checkOracleTarget(t, target["type"].(string), target["dsn"].(string))
		})
	}
}

// checkOracleTarget spot-checks converted values and the folded names.
func checkOracleTarget(t *testing.T, kind, dsn string) {
	t.Helper()
	driver := map[string]string{"sqlite": "sqlite3", "postgres": "postgres", "mysql": "mysql"}[kind]
	if kind == "mysql" {
		// mysql://user:pw@host:port/db -> user:pw@tcp(host:port)/db
		u, err := url.Parse(dsn)
		if err != nil {
			t.Fatal(err)
		}
		pw, _ := u.User.Password()
		dsn = fmt.Sprintf("%s:%s@tcp(%s)%s", u.User.Username(), pw, u.Host, u.Path)
	}
	db, err := sql.Open(driver, dsn)
	if err != nil {
		t.Fatal(err)
	}
	defer db.Close()
	one := func(q string) string {
		t.Helper()
		var s sql.NullString
		if err := db.QueryRow(q).Scan(&s); err != nil {
			t.Fatalf("%s: %v", q, err)
		}
		return s.String
	}
	if n := one(`SELECT COUNT(*) FROM xfdb_customers`); n != fmt.Sprint(oracleRows) {
		t.Errorf("customers: %s rows", n)
	}
	if n := one(`SELECT COUNT(*) FROM xfdb_order_lines`); n != fmt.Sprint(2*oracleRows) {
		t.Errorf("order lines: %s rows", n)
	}
	if got := one(`SELECT full_name FROM xfdb_customers WHERE id = 7`); got != "Zoë Müller 7" {
		t.Errorf("full_name = %q", got)
	}
	if got := one(`SELECT balance FROM xfdb_customers WHERE id = 7`); got != "8.75" {
		t.Errorf("balance = %q, want 8.75", got)
	}
	if got := one(`SELECT LENGTH(notes) FROM xfdb_customers WHERE id = 1`); got != "4101" {
		t.Errorf("CLOB length = %s, want 4101", got)
	}
	if got := one(`SELECT COUNT(*) FROM xfdb_customers WHERE empty_text IS NULL`); got != fmt.Sprint(oracleRows) {
		t.Errorf("Oracle's '' should arrive as NULL: %s NULL rows", got)
	}
	mixed := `SELECT "Label" FROM "XfdbMixed" WHERE "Id" = 2`
	if kind == "mysql" {
		mixed = "SELECT `Label` FROM `XfdbMixed` WHERE `Id` = 2"
	}
	if got := one(mixed); got != "two" {
		t.Errorf("quoted mixed-case table: %q", got)
	}
	tenure := one(`SELECT tenure FROM xfdb_customers WHERE id = 1`)
	if kind == "postgres" {
		if tenure != "1 year 2 mons" {
			t.Errorf("tenure = %q", tenure)
		}
		if got := one(`SELECT data_type FROM information_schema.columns WHERE table_name = 'xfdb_orders' AND column_name = 'id'`); got != "bigint" {
			t.Errorf("orders.id type = %s, want bigint", got)
		}
		if got := one(`SELECT to_char(seen_at AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS.US') FROM xfdb_customers WHERE id = 1`); got != "2025-03-04 10:07:07.123456" {
			t.Errorf("seen_at (UTC) = %s", got)
		}
		idx := one(`SELECT string_agg(indexname, ',' ORDER BY indexname) FROM pg_indexes WHERE tablename = 'xfdb_customers'`)
		if !strings.Contains(idx, "xfdb_customers_email_uk") || !strings.Contains(idx, "xfdb_customers_status_ix") || strings.Contains(idx, "lower") {
			t.Errorf("customers indexes: %s", idx)
		}
		if fk := one(`SELECT COUNT(*) FROM information_schema.table_constraints WHERE table_name = 'xfdb_orders' AND constraint_type = 'FOREIGN KEY'`); fk != "1" {
			t.Errorf("orders foreign keys: %s", fk)
		}
	} else if tenure != "P1Y2M" {
		t.Errorf("tenure = %q, want P1Y2M", tenure)
	}
	// The identity column still generates keys on the target, past every
	// copied one (#194). Validation has already run, so the row is harmless.
	if _, err := db.Exec(`INSERT INTO xfdb_orders (customer_id, total) VALUES (1, 1)`); err != nil {
		t.Errorf("insert without a key into the identity column: %v", err)
	} else if id, _ := strconv.Atoi(one(`SELECT MAX(id) FROM xfdb_orders`)); id <= oracleRows {
		t.Errorf("new order got key %d, want one past %d", id, oracleRows)
	}
}

func postJSON(t *testing.T, url string, body any, want int) map[string]any {
	t.Helper()
	data, _ := json.Marshal(body)
	resp, err := http.Post(url, "application/json", bytes.NewReader(data))
	if err != nil {
		t.Fatalf("POST %s: %v", url, err)
	}
	defer resp.Body.Close()
	var out map[string]any
	json.NewDecoder(resp.Body).Decode(&out) //nolint:errcheck
	if resp.StatusCode != want {
		t.Fatalf("POST %s: status %d: %v", url, resp.StatusCode, out)
	}
	return out
}

func getJSON(t *testing.T, url string, out any) {
	t.Helper()
	resp, err := http.Get(url)
	if err != nil {
		t.Fatalf("GET %s: %v", url, err)
	}
	defer resp.Body.Close()
	if err := json.NewDecoder(resp.Body).Decode(out); err != nil {
		t.Fatalf("GET %s: %v", url, err)
	}
}
