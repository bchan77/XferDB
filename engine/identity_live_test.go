// TestIdentityLive migrates a table whose key the database generates
// between every pair of PostgreSQL, MySQL and SQLite (#194), then inserts a
// row on the target that leaves the key out. It must get a key, and not
// one a copied row has: past the largest copied key, and on PostgreSQL and
// MySQL targets past the source's own next value, which is ahead of the
// rows (the row it last handed out was deleted). A copied key of 0 must stay
// 0: a MySQL AUTO_INCREMENT column turns an inserted 0 into a new key unless
// the session says otherwise. Needs XFERDB_TEST_PAIRS_PG and
// XFERDB_TEST_PAIRS_MYSQL, like TestColumnDefaultsLive.
func TestIdentityLive(t *testing.T) {
	pgAddr, myAddr := os.Getenv("XFERDB_TEST_PAIRS_PG"), os.Getenv("XFERDB_TEST_PAIRS_MYSQL")
	if pgAddr == "" || myAddr == "" {
		t.Skip("XFERDB_TEST_PAIRS_PG / XFERDB_TEST_PAIRS_MYSQL not set; skipping live identity test")
	}
	dir := t.TempDir()
	open := pairOpener(t, dir, pgAddr, myAddr)

	ddl := map[string][]string{
		"postgres": {
			`CREATE TABLE ident (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text)`,
			`CREATE TABLE ser (id serial PRIMARY KEY, name text)`,
		},
		"mysql": {
			`CREATE TABLE ident (id bigint AUTO_INCREMENT PRIMARY KEY, name text)`,
			`CREATE TABLE ser (id int AUTO_INCREMENT PRIMARY KEY, name text)`,
		},
		"sqlite": {
			`CREATE TABLE ident (id INTEGER PRIMARY KEY, name TEXT)`,
			`CREATE TABLE ser (id INTEGER PRIMARY KEY, name TEXT)`,
		},
	}
	types := []string{"postgres", "mysql", "sqlite"}
	for _, sn := range types {
		for _, tn := range types {
			t.Run(sn+"_to_"+tn, func(t *testing.T) {
				ctx := context.Background()
				name := fmt.Sprintf("ident_%s_%s_%d", sn[:2], tn[:2], time.Now().UnixNano()%1e6)
				src, scfg := open(sn, name+"_s")
				defer src.Close()
				// One connection, so the MySQL session setting holds for
				// the inserts.
				conn, err := src.Conn(ctx)
				if err != nil {
					t.Fatal(err)
				}
				if sn == "mysql" {
					if _, err := conn.ExecContext(ctx, "SET SESSION sql_mode = CONCAT(@@sql_mode, ',NO_AUTO_VALUE_ON_ZERO')"); err != nil {
						t.Fatal(err)
					}
				}
				for _, stmt := range ddl[sn] {
					if _, err := conn.ExecContext(ctx, stmt); err != nil {
						t.Fatalf("%v\n%s", err, stmt)
					}
				}
				for _, table := range []string{"ident", "ser"} {
					for _, stmt := range []string{
						`INSERT INTO ` + table + ` (id, name) VALUES (0, 'zero')`,
						`INSERT INTO ` + table + ` (name) VALUES ('a')`,
						`INSERT INTO ` + table + ` (name) VALUES ('b')`,
						`INSERT INTO ` + table + ` (name) VALUES ('c')`,
						`DELETE FROM ` + table + ` WHERE name = 'c'`,
					} {
						if _, err := conn.ExecContext(ctx, stmt); err != nil {
							t.Fatalf("%v\n%s", err, stmt)
						}
					}
				}
				conn.Close()
				tgt, tcfg := open(tn, name+"_t")
				defer tgt.Close()

				runPairMigration(t, dir, name, scfg, tcfg)

				// SQLite hands out the largest key plus one, as a SQLite
				// source did; the others continue from the source's next
				// value, past the deleted row.
				want := int64(4)
				if sn == "sqlite" || tn == "sqlite" {
					want = 3
				}
				for _, table := range []string{"ident", "ser"} {
					var zero string
					if err := tgt.QueryRow(`SELECT name FROM ` + table + ` WHERE id = 0`).Scan(&zero); err != nil || zero != "zero" {
						t.Errorf("%s: the row with key 0 reads %q, %v", table, zero, err)
					}
					execDB(t, tgt, `INSERT INTO `+table+` (name) VALUES ('new')`)
					var id int64
					if err := tgt.QueryRow(`SELECT id FROM ` + table + ` WHERE name = 'new'`).Scan(&id); err != nil {
						t.Fatalf("%s: %v", table, err)
					}
					if id != want {
						t.Errorf("%s: a new row got key %d, want %d", table, id, want)
					}
				}
			})
		}
	}
}

// runPairMigration migrates every table from scfg to tcfg with a metadb
// of its own in dir.
func runPairMigration(t *testing.T, dir, name string, scfg, tcfg adapters.ConnectionConfig) {
	t.Helper()
	ctx := context.Background()
	meta, err := state.Open(filepath.Join(dir, name+".state"))
	if err != nil {
		t.Fatal(err)
	}
	defer meta.Close()
	p := &adapters.Project{ID: name, Name: name, SourceConfig: scfg, TargetConfig: tcfg, CreatedAt: time.Now()}
	if err := meta.CreateProject(ctx, p); err != nil {
		t.Fatal(err)
	}
	mig := &adapters.Migration{ID: name, ProjectID: p.ID, Status: adapters.StatusPending, CreatedAt: time.Now()}
	if err := meta.CreateMigration(ctx, mig); err != nil {
		t.Fatal(err)
	}
	if err := New(mig.ID, p, meta).Run(ctx); err != nil {
		t.Fatalf("migration: %v", err)
	}
}
